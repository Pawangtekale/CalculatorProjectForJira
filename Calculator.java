class Calculator
{
	public static double isAddition(double a,double b){
		double sum=a+b;
		return sum;
	}
	public static double isSubstraction(double a,double b){
		double sub=a-b;
		return sub;
	}
	public static void main(String[] args) 
	{
		//isAddition(2,2);
		System.out.println(isAddition(2,2));
		System.out.println(isSubstraction(4,2));
		
	}
}

